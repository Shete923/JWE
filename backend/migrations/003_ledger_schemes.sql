BEGIN;

ALTER TABLE jewellery.ledger
    ADD COLUMN opening_gold_grams NUMERIC(12, 3) NOT NULL DEFAULT 0
        CHECK (opening_gold_grams >= 0),
    ADD COLUMN opening_silver_grams NUMERIC(12, 3) NOT NULL DEFAULT 0
        CHECK (opening_silver_grams >= 0);

CREATE SEQUENCE jewellery.scheme_no_seq AS BIGINT START WITH 1;

CREATE TABLE jewellery.savings_scheme (
    scheme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_no TEXT NOT NULL UNIQUE,
    branch_id BIGINT NOT NULL REFERENCES jewellery.shop_settings (branch_id),
    customer_id BIGINT NOT NULL REFERENCES jewellery.ledger (ledger_id),
    scheme_type TEXT NOT NULL CHECK (
        scheme_type IN ('A (11+1 Mo.)', 'B (12 Mo.)', 'Custom')
    ),
    start_date DATE NOT NULL,
    tenure_months SMALLINT NOT NULL CHECK (tenure_months BETWEEN 1 AND 120),
    monthly_contribution NUMERIC(14, 2) NOT NULL CHECK (monthly_contribution > 0),
    bonus_amount NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (bonus_amount >= 0),
    description TEXT NOT NULL CHECK (length(trim(description)) > 0),
    reminder_date DATE,
    status TEXT NOT NULL DEFAULT 'Running'
        CHECK (status IN ('Running', 'Completed', 'Cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE jewellery.scheme_installment (
    installment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id BIGINT NOT NULL REFERENCES jewellery.savings_scheme (scheme_id)
        ON DELETE CASCADE,
    installment_no SMALLINT NOT NULL CHECK (installment_no BETWEEN 1 AND 120),
    payment_date DATE NOT NULL,
    paid_amount NUMERIC(14, 2) NOT NULL CHECK (paid_amount > 0),
    gold_rate NUMERIC(14, 4) NOT NULL DEFAULT 0 CHECK (gold_rate >= 0),
    late_fine NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (late_fine >= 0),
    payment_mode TEXT NOT NULL
        CHECK (payment_mode IN ('Cash', 'Bank', 'UPI', 'NEFT / RTGS', 'Cheque')),
    transaction_reference TEXT,
    deposit_bank TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_scheme_installment_number UNIQUE (scheme_id, installment_no)
);

CREATE INDEX ix_savings_scheme_customer
    ON jewellery.savings_scheme (branch_id, customer_id, scheme_id DESC);
CREATE INDEX ix_scheme_installment_date
    ON jewellery.scheme_installment (scheme_id, payment_date DESC);

COMMIT;
